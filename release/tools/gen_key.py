#!/usr/bin/env python3
"""Generate an Ed25519 keypair for image signing.

Writes:
    keys/dev_signing.key   32-byte seed, hex (keep secret)
    keys/dev_public.key    32-byte public key, hex
    bootloader/Src/ab_pubkey.c   public key compiled into the bootloader

The path names are dev-oriented on purpose: a production key should live
outside the repository and only the public half should be committed.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from nacl.signing import SigningKey

ROOT = Path(__file__).resolve().parents[1]


def c_array(pub: bytes) -> str:
    lines = [
        "/* Auto-generated by tools/gen_key.py. Replace with your own key. */",
        "#include <stdint.h>",
        "",
        "const uint8_t ab_pubkey[32] = {",
    ]
    for i in range(0, 32, 8):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in pub[i : i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", default="keys")
    parser.add_argument("--pubkey-c", default="bootloader/Src/ab_pubkey.c")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    out_dir = ROOT / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    secret = out_dir / "dev_signing.key"
    public = out_dir / "dev_public.key"

    if secret.exists() and not args.force:
        raise SystemExit(f"{secret} already exists; pass --force to overwrite")

    key = SigningKey.generate()
    seed = bytes(key)
    pub = bytes(key.verify_key)

    secret.write_text(seed.hex(), encoding="utf-8")
    public.write_text(pub.hex(), encoding="utf-8")
    (ROOT / args.pubkey_c).write_text(c_array(pub), encoding="utf-8")

    print(f"private: {secret}")
    print(f"public : {public}")
    print(f"header : {args.pubkey_c}")
    print("commit the public key, never the private one")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
